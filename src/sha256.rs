//! SHA-256 implemented from scratch, no external crates.
//!
//! Follows FIPS 180-4. Verified against the standard empty-string and "abc"
//! known-answer vectors in the unit tests below.

// The round constants are transcribed verbatim from FIPS 180-4 section 4.2.3
// so they can be diffed against the standard, so no digit separators.
